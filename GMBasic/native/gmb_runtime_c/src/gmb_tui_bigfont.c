const uint8_t* gmb_bigfont_row(uint32_t key, int* out_width)
{
    if (out_width) *out_width = 5;
    /* minuscole ASCII -> maiuscole (come BigTextFont.Get) */
    if (key >= 'a' && key <= 'z') key = key - 'a' + 'A';
    for (size_t i = 0; i < sizeof(g_bigfont) / sizeof(g_bigfont[0]); i++)
        if (g_bigfont[i].cp == key) return g_bigfont[i].rows;
    for (size_t i = 0; i < sizeof(g_bigfont) / sizeof(g_bigfont[0]); i++)
        if (g_bigfont[i].cp == '?') return g_bigfont[i].rows;
    return NULL;
}

int gmb_bigfont_count(void) { return (int)(sizeof(g_bigfont) / sizeof(g_bigfont[0])); }
