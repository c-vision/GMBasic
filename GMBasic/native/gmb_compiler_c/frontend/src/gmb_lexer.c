static gmb_tokenkind_t keyword_lookup(const char* word, int len)
{
    for (int i = 0; gmb_keywords[i].word; i++) {
        const char* w = gmb_keywords[i].word;
        size_t wl = strlen(w);
        if (wl == (size_t)len && strncasecmp(w, word, len) == 0)
            return gmb_keywords[i].kind;
    }
    return GMB_TOK_Identifier;
}

int gmb_keyword_tok(const char* word)
{
    if (!word) return -1;
    return (int)keyword_lookup(word, (int)strlen(word));
}

/* ── output buffer ── */
static gmb_lex_result_t gmb_lex_result_new(void)
{
    gmb_lex_result_t r = {0};
    r.cap = 256;
    r.tokens = (gmb_token_t*)malloc((size_t)r.cap * sizeof(gmb_token_t));
    return r;
}

static void gmb_lex_push(gmb_lex_result_t* r, gmb_tokenkind_t kind, const char* lex, int len, int line, int col)
{
    if (r->count >= r->cap) {
        r->cap *= 2;
        r->tokens = (gmb_token_t*)realloc(r->tokens, (size_t)r->cap * sizeof(gmb_token_t));
    }
    gmb_token_t* t = &r->tokens[r->count++];
    t->kind = kind; t->lexeme = lex; t->length = len; t->line = line; t->col = col;
}

