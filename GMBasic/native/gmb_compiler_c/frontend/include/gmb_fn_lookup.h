/* Nome (grafie StdLib non ambigue o nome enum canonico) → TokenKind; Unknown altrove. */
static inline gmb_tokenkind_t gmb_fn_tok(const char* n)
{
    if (!n) return GMB_TOK_Unknown;
    for (size_t i = 0; i < sizeof(gmb_fn_lookup) / sizeof(gmb_fn_lookup[0]); i++)
        if (strcasecmp(n, gmb_fn_lookup[i].k) == 0) return gmb_fn_lookup[i].tk;
    return GMB_TOK_Unknown;
}
