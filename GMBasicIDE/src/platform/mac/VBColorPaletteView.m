- (BOOL)isFlipped { return YES; }

- (NSSize)intrinsicContentSize
{
    return NSMakeSize(kMargin * 2 + kColumns * kCell, kMargin * 2 + 8 * kCell);
}

- (void)drawRect:(NSRect)dirtyRect
{
    (void)dirtyRect;
    VBFillFace(self.bounds);
    for (NSUInteger i = 0; i < _colors.count; i++) {
        CGFloat x = kMargin + (i % 8) * kCell;
        CGFloat y = kMargin + (i / 8) * kCell;
        NSRect cell = NSMakeRect(x, y, kCell - 1, kCell - 1);
        [[VBColorWindow() colorWithAlphaComponent:0.65] setFill];
        NSRectFill(cell);
        [_colors[i] setFill];
        NSRectFill(NSInsetRect(cell, 1, 1));
        [[VBColorShadow() colorWithAlphaComponent:0.7] setStroke];
        [NSBezierPath strokeRect:NSInsetRect(cell, 0.5, 0.5)];
    }
}

- (void)mouseDown:(NSEvent *)event
{
    NSPoint p = [self convertPoint:event.locationInWindow fromView:nil];
    NSInteger column = (NSInteger)floor((p.x - kMargin) / kCell);
    NSInteger row = (NSInteger)floor((p.y - kMargin) / kCell);
    if (column < 0 || column >= 8 || row < 0 || row >= 8) return;
    NSInteger index = row * 8 + column;
    if (index < 0 || index >= (NSInteger)_colors.count) return;
    if (self.target && self.action && [self.target respondsToSelector:self.action]) {
        IMP imp = [self.target methodForSelector:self.action];
        if (imp) ((void (*)(id, SEL, id))imp)(self.target, self.action, _colors[(NSUInteger)index]);
    }
}

@end
